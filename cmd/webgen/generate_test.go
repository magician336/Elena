// TestGenerateIsByteForByteDeterministic is the page data's contract:
// the same seed and the same raw benchmark documents produce the same
// bytes — twice, against two fresh store directories — while a
// different seed produces different bytes. The page's data file can be
// regenerated at any time and land exactly where it was.
func TestGenerateIsByteForByteDeterministic(t *testing.T) {
	first, err := Generate(GenerateInput{Seed: 1, DataDir: realDataDir})
	if err != nil {
		t.Fatalf("first generate: %v", err)
	}
	second, err := Generate(GenerateInput{Seed: 1, DataDir: realDataDir})
	if err != nil {
		t.Fatalf("second generate: %v", err)
	}
	if !bytes.Equal(first, second) {
		t.Fatalf("same seed generated different bytes (%d vs %d); determinism is broken",
			len(first), len(second))
	}

	other, err := Generate(GenerateInput{Seed: 2, DataDir: realDataDir})
	if err != nil {
		t.Fatalf("seed-2 generate: %v", err)
	}
	if bytes.Equal(first, other) {
		t.Fatalf("seeds 1 and 2 generated identical bytes; the seed must drive the payloads")
	}
}

// TestRenderEmitsScriptIncludableForm pins the output's shape for the
// file:// constraint: a browser that opened the page straight off the
// disk cannot fetch cross-origin, so the data must arrive as one plain
// script-assignable expression — a const declaration whose payload is
// valid JSON, ending in a newline.
func TestRenderEmitsScriptIncludableForm(t *testing.T) {
	out, err := Generate(GenerateInput{Seed: 1, DataDir: realDataDir})
	if err != nil {
		t.Fatalf("generate: %v", err)
	}
	if !bytes.HasPrefix(out, []byte("const DATA = ")) {
		t.Fatalf("output must open with a const DATA declaration, got %q", firstN(out, 40))
	}
	if !bytes.HasSuffix(out, []byte(";\n")) {
		t.Fatalf("output must end with a semicolon and one newline, got tail %q", lastN(out, 20))
	}
	body := strings.TrimSuffix(strings.TrimPrefix(string(out), "const DATA = "), ";\n")
	if !json.Valid([]byte(body)) {
		t.Fatalf("the declared value must be valid JSON")
	}
	var data struct {
		Meta       map[string]any    `json:"meta"`
		Trajectory map[string]any    `json:"trajectory"`
		Checkpoint map[string]any    `json:"checkpoint"`
		Benchmarks map[string]any    `json:"benchmarks"`
	}
	if err := json.Unmarshal([]byte(body), &data); err != nil {
		t.Fatalf("decode: %v", err)
	}
	for _, act := range []string{"meta", "trajectory", "checkpoint", "benchmarks"} {
		switch act {
		case "meta":
			if data.Meta == nil {
				t.Fatalf("meta section missing")
			}
		case "trajectory":
			if data.Trajectory == nil {
				t.Fatalf("trajectory section missing")
			}
		case "checkpoint":
			if data.Checkpoint == nil {
				t.Fatalf("checkpoint section missing")
			}
		case "benchmarks":
			if data.Benchmarks == nil {
				t.Fatalf("benchmarks section missing")
			}
		}
	}
	if got := data.Meta["seed"]; got != float64(1) {
		t.Fatalf("meta.seed = %v, want 1", got)
	}
}

// TestRunWritesTheFile drives the command's wiring end to end: run
// writes the generated bytes to the requested path.
func TestRunWritesTheFile(t *testing.T) {
	outPath := filepath.Join(t.TempDir(), "data.js")
	if err := run(outPath, realDataDir, 1); err != nil {
		t.Fatalf("run: %v", err)
	}
	written, err := os.ReadFile(outPath)
	if err != nil {
		t.Fatalf("read back: %v", err)
	}
	if !bytes.HasPrefix(written, []byte("const DATA = ")) {
		t.Fatalf("written file must open with the const declaration")
	}
}

// firstN and lastN return short excerpts for failure messages.
func firstN(b []byte, n int) string { return excerpt(b, 0, n) }
func lastN(b []byte, n int) string  { return excerpt(b, len(b)-n, len(b)) }

func excerpt(b []byte, from, to int) string {
	if from < 0 || to > len(b) || from >= to {
		return ""
	}
	return string(b[from:to])
}
